def main() -> int:
    data = json.loads(OUT.read_text(encoding="utf-8"))
    patterns = data["patterns"]
    have = {p["id"] for p in patterns}
    added = 0
    for pid, match, name, level, z, ex in NEW:
        if pid in have:
            continue
        patterns.append({"id": pid, "match": match, "name": name,
                         "level": level, "z": z, "ex": ex})
        added += 1
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                   encoding="utf-8")
    import collections
    print(f"added {added}, total {len(patterns)}")
    print("levels:", dict(collections.Counter(p["level"] for p in patterns)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
