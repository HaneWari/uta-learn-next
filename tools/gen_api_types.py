"""Generate `frontend/src/api-types.ts` from the backend's OpenAPI document.

The hand-written `types.ts` drifted from the routes more than once (a renamed
field kept compiling because both sides were edited separately). This script
imports the app, dumps the schema and runs `openapi-typescript`, so the
generated file is a build artefact rather than another thing to maintain.

CI re-runs it and fails on a diff, which is what keeps it honest.

    python tools/gen_api_types.py            # write
    python tools/gen_api_types.py --check    # exit 1 when out of date
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKEND = ROOT / "backend"
OUT = ROOT / "frontend" / "src" / "api-types.ts"

HEADER = """// AUTO-GENERATED by tools/gen_api_types.py — do not edit by hand.
// Regenerate with `python tools/gen_api_types.py`; CI fails when this file is
// out of date with the backend's OpenAPI schema.
"""


def dump_openapi() -> str:
    sys.path.insert(0, str(BACKEND))
    import json
    import os
    import tempfile

    # importing the app must not touch the user's real data directory
    os.environ.setdefault("DATA_DIR", tempfile.mkdtemp(prefix="uta-genapi-"))
    os.environ.setdefault("EXPORT_DIR", tempfile.mkdtemp(prefix="uta-genexp-"))
    os.environ.setdefault("UTALEARN_DEV", "1")
    import main  # noqa: PLC0415  (the path above has to be set first)

    return json.dumps(main.app.openapi(), ensure_ascii=False)


def main() -> int:
    check = "--check" in sys.argv
    schema = dump_openapi()
    staging = ROOT / "frontend" / ".openapi.json"
    staging.write_text(schema, encoding="utf-8")
    tmp_out = OUT.with_suffix(".ts.tmp")
    try:
        # Windows resolves `npx` through a .cmd shim, which subprocess cannot
        # exec without a shell; `shell=True` is safe here (no user input).
        subprocess.run(
            ["npx", "--yes", "openapi-typescript", str(staging),
             "-o", str(tmp_out)],
            cwd=ROOT / "frontend", check=True, shell=sys.platform == "win32",
        )
        body = tmp_out.read_text(encoding="utf-8")
        generated = HEADER + body
        if check:
            current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
            if _normalise(current) != _normalise(generated):
                for line in _first_diff(_normalise(current), _normalise(generated)):
                    print(line, file=sys.stderr)
                print("api-types.ts 与后端 schema 不一致,请运行 "
                      "`python tools/gen_api_types.py`", file=sys.stderr)
                return 1
            print("api-types.ts 已是最新")
            return 0
        OUT.write_text(generated, encoding="utf-8")
        print(f"已写入 {OUT.relative_to(ROOT)}")
        return 0
    finally:
        tmp_out.unlink(missing_ok=True)
        staging.unlink(missing_ok=True)


def _normalise(text: str) -> str:
    """Ignore trailing whitespace and line endings when comparing.

    The generator runs on Windows locally and Linux in CI; CRLF and trailing
    spaces must not be treated as schema drift.
    """
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").split("\n")]
    return "\n".join(lines).strip() + "\n"


def _first_diff(a: str, b: str) -> list[str]:
    """A short, readable diff so a CI failure says *what* drifted."""
    import difflib

    diff = list(difflib.unified_diff(
        a.splitlines(), b.splitlines(), "on-disk", "from-openapi", lineterm=""))
    return diff[:40]


if __name__ == "__main__":
    raise SystemExit(main())
